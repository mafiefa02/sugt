-- One online Session per School per day.
--
-- `data-model.md` has carried this index in its *Decided, not applied* table since the
-- schema was written, and Jadwalkan Sesi daring is the screen that makes it necessary:
-- online Sessions are arranged from Coverage in a batch, one date applied across a
-- multi-selection, so "the same School twice on the same day" is one mis-click away
-- rather than theoretical.
--
-- `session_one_per_school_per_perjadin` cannot catch it. That index keys on
-- `perjadin_id`, every online Session has none, and Postgres treats NULLs in a unique
-- index as distinct — so two online Sessions for one School on one date never collided
-- with anything.
--
-- Partial in both the ways that index is, and for the same two reasons. `status <>
-- 'cancelled'` because cancelled Sessions accumulate and a School whose Session was
-- called off and re-arranged on the same date must not collide with its own dead row.
-- `perjadin_id is null` because offline Sessions are the first index's business, and one
-- Perjadin visiting a School on the same date an online Session was arranged for is a
-- legal pair.
--
-- Generated by drizzle-kit from `src/schema/delivery.ts`, unlike 0001 and 0003 — this
-- one is in the snapshot under `meta/`, so `generate` knows about it and will not
-- propose it again.

CREATE UNIQUE INDEX "session_one_online_per_school_per_day" ON "session" USING btree ("school_id","held_on") WHERE perjadin_id is null and status <> 'cancelled';
